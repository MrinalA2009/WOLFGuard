def get_all_raw_controls() -> list[RawControl]:
    controls: list[RawControl] = []
    for prompt in _NORMAL_FACTUAL_QA:
        controls.append(RawControl(control_type="normal_factual_qa", prompt=prompt))
    for prompt in _CREATIVE_WRITING:
        controls.append(RawControl(control_type="creative_writing", prompt=prompt))
    for prompt in _HARMLESS_ROLEPLAY:
        controls.append(RawControl(control_type="harmless_roleplay", prompt=prompt))
    for prompt in _UNCERTAINTY_EXPLANATION:
        controls.append(RawControl(control_type="uncertainty_explanation", prompt=prompt))
    for prompt in _NONDECEPTIVE_PERSUASION:
        controls.append(RawControl(control_type="nondeceptive_persuasion", prompt=prompt))
    for prompt in _INSTRUCTION_FOLLOWING:
        controls.append(RawControl(control_type="instruction_following", prompt=prompt))
    return controls
